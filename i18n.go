package main

func (a *app) tr(key string) string {
	a.mu.Lock()
	lang := a.uiLang
	a.mu.Unlock()
	return lookup(lang, key)
}

func lookup(lang, key string) string {
	if lang != "en" {
		lang = "cn"
	}
	if s, ok := messages[lang][key]; ok {
		return s
	}
	if s, ok := messages["en"][key]; ok {
		return s
	}
	return key
}

